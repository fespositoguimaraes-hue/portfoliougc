-- lista = 'dia'    → tarefas do dia (area: 'pessoal' ou 'trabalho', dia: a data)
-- lista = 'macro'  → tarefas macro
-- lista = 'ideias' → ideias de conteúdo (formato, agendada_para)
--
-- Só você (logada no admin) consegue ver, criar, editar e apagar itens.
-- Visitantes do site não têm acesso nenhum a esta tabela.
--
-- Onde rodar: painel do Supabase > seu projeto > SQL Editor > New query
-- Cole tudo e clique em "Run".
-- ============================================================================

create table if not exists checklist_itens (
  id bigint generated by default as identity primary key,
  lista text not null,
  texto text not null,
  feita boolean not null default false,
  area text,
  dia date,
  formato text,
  agendada_para date,
  criado_em timestamptz not null default now()
);

alter table checklist_itens enable row level security;

drop policy if exists "checklist_itens: so a dona" on checklist_itens;
create policy "checklist_itens: so a dona"
  on checklist_itens for all
  to authenticated
  using (true)
  with check (true);

-- Traz as ideias que já estavam na antiga aba "Ideias" (só na primeira vez)
insert into checklist_itens (lista, texto, formato, feita, agendada_para, criado_em)
select 'ideias', texto, formato, feita, agendada_para, criado_em from ideias_conteudo
where not exists (select 1 from checklist_itens where lista = 'ideias');
