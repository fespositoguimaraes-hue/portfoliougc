-- ============================================================================
-- ABA "FINANÇAS" DO ADMIN: cria a tabela onde ficam suas entradas e saídas
-- ============================================================================
-- Cada lançamento é marcado como EMPRESA (criadora de conteúdo) ou PESSOAL,
-- assim as duas finanças nunca se misturam.
--
-- Só você (logada no admin) consegue ver, criar, editar e apagar.
-- Visitantes do site não têm acesso nenhum a esta tabela.
--
-- Onde rodar: painel do Supabase > seu projeto > SQL Editor > New query
-- Cole tudo e clique em "Run".
-- ============================================================================

create table if not exists financas (
  id bigint generated by default as identity primary key,
  ambito text not null check (ambito in ('empresa', 'pessoal')),
  tipo text not null check (tipo in ('entrada', 'saida')),
  descricao text not null,
  categoria text,
  valor numeric(12, 2) not null check (valor >= 0),
  data date not null,
  status text not null default 'confirmado' check (status in ('confirmado', 'pendente')),
  obs text,
  nf text check (nf in ('emitida', 'nao_emitida')),
  nf_numero text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

-- Nota fiscal (só para entradas da empresa):
--   nf = 'emitida' | 'nao_emitida' | vazio (não informado)
-- As linhas abaixo garantem as colunas mesmo se a tabela já existia antes.
alter table financas add column if not exists nf text check (nf in ('emitida', 'nao_emitida'));
alter table financas add column if not exists nf_numero text;

-- Data em que o trabalho foi FECHADO (só entradas da empresa).
-- A coluna "data" continua sendo a data do pagamento (previsto ou recebido).
alter table financas add column if not exists data_fechamento date;

create index if not exists financas_data_idx on financas (data);

alter table financas enable row level security;

drop policy if exists "financas: so a dona" on financas;
create policy "financas: so a dona"
  on financas for all
  to authenticated
  using (true)
  with check (true);
