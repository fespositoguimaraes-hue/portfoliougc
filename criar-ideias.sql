create table if not exists ideias_conteudo (
  id bigint generated by default as identity primary key,
  texto text not null,
  formato text,
  feita boolean not null default false,
  agendada_para date,
  criado_em timestamptz not null default now()
);

alter table ideias_conteudo enable row level security;

drop policy if exists "ideias_conteudo: so a dona" on ideias_conteudo;
create policy "ideias_conteudo: so a dona"
  on ideias_conteudo for all
  to authenticated
  using (true)
  with check (true);
