create table if not exists estrategia_itens (
  id bigint generated by default as identity primary key,
  secao text not null,
  titulo text not null,
  detalhe text,
  texto text,
  criado_em timestamptz not null default now()
);

alter table estrategia_itens enable row level security;

drop policy if exists "estrategia_itens: so a dona" on estrategia_itens;
create policy "estrategia_itens: so a dona"
  on estrategia_itens for all
  to authenticated
  using (true)
  with check (true);
