create table if not exists posts_calendario (
  id bigint generated by default as identity primary key,
  titulo text not null,
  data date not null,
  tipo text not null default 'Reels',
  publicado boolean not null default false,
  obs text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

alter table posts_calendario enable row level security;

drop policy if exists "posts_calendario: so a dona" on posts_calendario;
create policy "posts_calendario: so a dona"
  on posts_calendario for all
  to authenticated
  using (true)
  with check (true);

-- Marca dos posts que performaram bem (referência para os próximos conteúdos)
alter table posts_calendario add column if not exists performou_bem boolean not null default false;
